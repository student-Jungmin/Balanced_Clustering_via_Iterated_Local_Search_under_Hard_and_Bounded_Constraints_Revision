#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

OMEGAS = [2, 3, 4, 5, 6, 7, 8, 9]
DELTAS = ["0.001", "0.005", "0.01", "0.05", "0.1"]
DEFAULT = (3, "0.001")


def per_dataset(path: Path, field: str) -> dict[str, float]:
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/calibration/run.sh first")
    acc = defaultdict(list)
    for r in csv.DictReader(path.open(), delimiter="\t"):
        acc[r["dataset"]].append(float(r[field]))
    return {d: statistics.fmean(v) for d, v in acc.items()}


def grids(root: Path):
    rkm_mse = per_dataset(root / "rkm" / "raw_runs.tsv", "mse")
    rkm_time = per_dataset(root / "rkm" / "raw_runs.tsv", "time_s")
    shape = (len(OMEGAS), len(DELTAS))
    out = {k: np.full(shape, np.nan) for k in
           ("max_mse", "avg_mse", "max_time", "avg_time")}
    for i, omega in enumerate(OMEGAS):
        for j, delta in enumerate(DELTAS):
            raw = root / "sweep" / f"w{omega}_d{delta}" / "raw_runs.tsv"
            mse, time = per_dataset(raw, "mse"), per_dataset(raw, "time_s")
            shared = [d for d in mse if d in rkm_mse and rkm_mse[d] > 0
                      and rkm_time.get(d, 0) > 0]
            mse_ratio = [mse[d] / rkm_mse[d] for d in shared]
            time_ratio = [time[d] / rkm_time[d] for d in shared]
            out["max_mse"][i, j] = max(mse_ratio)
            out["avg_mse"][i, j] = statistics.fmean(mse_ratio)
            out["max_time"][i, j] = max(time_ratio)
            out["avg_time"][i, j] = statistics.fmean(time_ratio)
    return out


def recorded(path: Path):
    out = {k: np.full((len(OMEGAS), len(DELTAS)), np.nan) for k in
           ("max_mse", "avg_mse", "max_time", "avg_time")}
    with path.open() as fh:
        rows = [ln for ln in fh if not ln.startswith("#")]
    for r in csv.DictReader(rows, delimiter="\t"):
        i = OMEGAS.index(int(r["omega"]))
        for j, d in enumerate(DELTAS):
            out[r["metric"]][i, j] = float(r["d" + d])
    return out


def heatmap(ax, grid, title, fmt):
    im = ax.imshow(grid, cmap="viridis_r", aspect="auto")
    ax.set_xticks(range(len(DELTAS)), DELTAS, fontsize=8)
    ax.set_yticks(range(len(OMEGAS)), OMEGAS, fontsize=8)
    ax.set_xlabel(r"$\delta$", fontsize=9)
    ax.set_ylabel(r"$\omega$", fontsize=9)
    ax.set_title(title, fontsize=9)
    lo, hi = np.nanmin(grid), np.nanmax(grid)
    for i in range(grid.shape[0]):
        for j in range(grid.shape[1]):
            shade = "white" if grid[i, j] > lo + 0.6 * (hi - lo) else "black"
            ax.text(j, i, format(grid[i, j], fmt), ha="center", va="center",
                    fontsize=7, color=shade)
    di, dj = OMEGAS.index(DEFAULT[0]), DELTAS.index(DEFAULT[1])
    ax.add_patch(plt.Rectangle((dj - 0.5, di - 0.5), 1, 1, fill=False,
                               edgecolor="red", linewidth=1.6))
    return im


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/calibration"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    ap.add_argument("--grid", default="results/calibration/published/grid.tsv",
                    help="recorded grid to draw; pass an empty path to "
                         "recompute from the sweep under --results")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    g = recorded(Path(a.grid)) if a.grid else grids(a.results)

    fig, axes = plt.subplots(2, 2, figsize=(7.2, 6.0))
    for ax, (key, title, fmt) in zip(axes.ravel(), [
            ("max_mse", "Max MSE ratio vs RKM", ".3f"),
            ("avg_mse", "Mean MSE ratio vs RKM", ".3f"),
            ("max_time", "Max time ratio vs RKM", ".3f"),
            ("avg_time", "Mean time ratio vs RKM", ".3f")]):
        im = heatmap(ax, g[key], title, fmt)
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.tight_layout()
    png = a.out / "fig_param_calibration.png"
    fig.savefig(png, dpi=300)
    print(f"  {png}")

    (a.out / "fig_param_calibration.tex").write_text(
        """% generated by experiments/calibration/figure.py -- do not edit
\\begin{figure}[!t]
\\centering
\\includegraphics[width=\\linewidth]{generated/fig_param_calibration.png}
\\caption{Calibration of the CV-based termination: maximum and mean MSE and runtime ratios to RKM over window size $\\omega$ and threshold $\\delta$; the red cell is the default. Transcribed from the submitted version, whose sweep predates this revision's optimizations; its raw runs were not archived.}
\\label{fig:param_calibration}
\\end{figure}
""")
    print(f"  {a.out / 'fig_param_calibration.tex'}")

    (a.out / "tab_termination_params.tex").write_text(f"""% generated by experiments/calibration/figure.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{Termination parameters: candidate values and defaults.}}
\\label{{tab:termination_params}}
\\begin{{tabularx}}{{\\columnwidth}}{{@{{}} l X c X @{{}}}}
\\toprule
Parameter & Candidate values & Default & Description \\\\
\\midrule
$T_{{\\max}}$ & Fixed & 100 & Maximum iteration \\\\ \\addlinespace
$\\omega$ & ${', '.join(str(o) for o in OMEGAS)}$ & {DEFAULT[0]} & Window size for CV \\\\ \\addlinespace
$\\delta$ & ${', '.join(DELTAS)}$ & {DEFAULT[1]} & Threshold for CV of SSE \\\\
\\bottomrule
\\end{{tabularx}}

\\smallskip

{{\\raggedright \\small \\textit{{Note:}} CV stands for the coefficient of variation.\\par}}
\\end{{table}}
""")
    print(f"  {a.out / 'tab_termination_params.tex'}")


if __name__ == "__main__":
    main()
