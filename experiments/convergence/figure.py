#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

VARIANTS = [("HBC", "HBC", "#1f4e79", "-"),
            ("HBC_WI", "HBC$_{\\mathregular{WI}}$", "#c0504d", "--")]
FLOOR = 1e-6
BAND_FLOOR = 1e-4


def terminations(path: Path):
    out = defaultdict(int)
    for r in csv.DictReader(path.open(), delimiter="\t"):
        key = (r["dataset"], r["seed"])
        out[key] = max(out[key], int(r["iter"]))
    return list(out.values())


def traces(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/convergence/run.sh first")
    by_run = defaultdict(dict)
    for r in csv.DictReader(path.open(), delimiter="\t"):
        by_run[(r["dataset"], r["seed"])][int(r["iter"])] = float(r["mse"])
    per_dataset = defaultdict(list)
    for (dataset, _), series in by_run.items():
        per_dataset[dataset].append([series[i] for i in sorted(series)])
    out = {}
    for dataset, runs in per_dataset.items():
        width = max(len(r) for r in runs)
        padded = np.array([r + [r[-1]] * (width - len(r)) for r in runs], dtype=float)
        out[dataset] = padded.mean(axis=0)
    return out


def panel(ax, results, ends, title):
    datasets = set.intersection(*(set(c) for c in results.values()))
    best = {d: min(results[k][d][-1] for k, _, _, _ in results_keys(results))
            for d in datasets}

    for key, label, colour, style in VARIANTS:
        curves = {d: results[key][d] for d in datasets}
        width = max(len(c) for c in curves.values())
        median, lo, hi, x = [], [], [], []
        for t in range(width):
            alive = [max(c[t] / best[d] - 1.0, FLOOR)
                     for d, c in curves.items() if t < len(c)]
            if len(alive) * 2 < len(curves):
                break
            x.append(t + 1)
            median.append(np.median(alive))
            q1, q3 = np.percentile(alive, [25, 75])
            lo.append(q1)
            hi.append(q3)
        ax.plot(x, median, style, color=colour, label=label, linewidth=1.8)
        ax.fill_between(x, lo, hi, color=colour, alpha=0.15, linewidth=0)

        ax.axvline(np.median(ends[key]), color=colour, linestyle=":", linewidth=1,
                   alpha=0.7)

    ax.set_yscale("log")
    ax.set_xlabel("ILS iteration")
    ax.set_title(title, fontsize=10)
    ax.grid(True, which="both", alpha=0.25, linewidth=0.5)
    ax.margins(x=0.02)


def results_keys(results):
    return [(k, l, c, s) for k, l, c, s in VARIANTS if k in results]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/pruning"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4), sharey=True)
    for ax, (scale, title) in zip(axes, [("standard", "Standard scale"),
                                         ("large", "Large scale")]):
        results = {k: traces(a.results / k / scale / "convergence.tsv")
                   for k, _, _, _ in VARIANTS}
        ends = {k: terminations(a.results / k / scale / "convergence.tsv")
                for k, _, _, _ in VARIANTS}
        panel(ax, results, ends, title)
    axes[0].set_ylabel("Excess over best reached")
    for ax in axes:
        ax.set_ylim(bottom=BAND_FLOOR)
    axes[0].legend(frameon=False, fontsize=9)
    fig.tight_layout()

    png = a.out / "fig_mse_convergence.png"
    fig.savefig(png, dpi=300)
    print(f"  {png}")

    (a.out / "fig_mse_convergence.tex").write_text(
        """% generated by experiments/convergence/figure.py -- do not edit
\\begin{figure}[htbp]
    \\centering
    \\includegraphics[width=\\linewidth]{generated/fig_mse_convergence.png}
    \\caption{Convergence of HBC and $\\text{HBC}_\\text{WI}$, which refines to convergence after every perturbation. Vertical axis: excess objective over the best value either variant reaches on each dataset. Line: median over datasets; band: interquartile range, clipped at the axis floor; dotted rules: median iterations performed.}
    \\label{fig:mse_convergence_per_iter}
\\end{figure}
""")
    print(f"  {a.out / 'fig_mse_convergence.tex'}")


if __name__ == "__main__":
    main()
