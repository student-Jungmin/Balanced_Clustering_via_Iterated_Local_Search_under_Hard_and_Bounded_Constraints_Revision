#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics
from collections import defaultdict
from pathlib import Path

VARIANTS = [("HBC", "HBC"), ("HBC_WI", r"HBC$_\text{WI}$")]


def read_final(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/convergence/run.sh first")
    performed: dict[tuple, int] = {}
    for r in csv.DictReader(path.open(), delimiter="\t"):
        key = (r["dataset"], r["seed"])
        performed[key] = max(performed.get(key, 0), int(r["iter"]))
    mse = {}
    for r in csv.DictReader((path.parent / "runs.tsv").open(), delimiter="\t"):
        mse[(r["dataset"], r["seed"])] = float(r["mse"])
    assert performed.keys() == mse.keys(), "trace and runs.tsv cover different runs"
    per_dataset = defaultdict(list)
    for key, it in performed.items():
        per_dataset[key[0]].append((it, mse[key]))
    return {d: (statistics.fmean(i for i, _ in v), statistics.fmean(m for _, m in v))
            for d, v in per_dataset.items()}


def sci(x: float) -> str:
    mantissa, exponent = f"{x:.2e}".split("e")
    sign = "{-}" if exponent[0] == "-" else "{+}"
    return rf"{mantissa}\mathrm{{e}}{sign}{int(exponent[1:])}"


def block(dataset, data) -> list[str]:
    iters = {k: data[k][dataset][0] for k, _ in VARIANTS}
    mses = {k: data[k][dataset][1] for k, _ in VARIANTS}
    best_iter, best_mse = min(iters.values()), min(mses.values())
    out = []
    for i, (key, label) in enumerate(VARIANTS):
        head = rf"\multirow{{2}}{{*}}{{{dataset}}}" if i == 0 else ""
        it = f"{iters[key]:.0f}"
        it = rf"\textbf{{{it}}}" if iters[key] <= best_iter else it
        cell = f"${sci(mses[key])}$ ({mses[key]/best_mse:.2f})"
        cell = rf"\textbf{{{cell}}}" if mses[key] <= best_mse * (1 + 1e-9) else cell
        out.append(f"{head} & {label} & {it} & {cell}")
    return out


def two_up(data) -> list[str]:
    datasets = sorted(data["HBC"], key=str.lower)
    half = (len(datasets) + 1) // 2
    left, right = datasets[:half], datasets[half:]
    rows = []
    for i in range(half):
        l = block(left[i], data)
        r = block(right[i], data) if i < len(right) else ["  &  &  & ", "  &  &  & "]
        rows.append(f"{l[0]} & {r[0]} \\\\")
        rows.append(f"{l[1]} & {r[1]} \\\\")
        rows.append(r"\addlinespace")
    return rows[:-1]


def table(per_scale, caption, label) -> str:
    blocks = []
    for name, data in per_scale:
        rows = [rf"\multicolumn{{8}}{{l}}{{\textit{{{name} scale}}}} \\"] + two_up(data)
        blocks.append("\n".join(rows))
    body = "\n\\midrule\n".join(blocks)
    return f"""% generated by experiments/convergence/tables.py -- do not edit
\\begin{{table*}}[!t]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\resizebox{{\\ifdim\\width>\\textwidth\\textwidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{0.8}}
\\begin{{tabular}}{{l l c c l l c c}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Method}} & \\textbf{{Iter.}} & \\textbf{{MSE}} & \\textbf{{Dataset}} & \\textbf{{Method}} & \\textbf{{Iter.}} & \\textbf{{MSE}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
}}
\\end{{table*}}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/pruning"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    scales = []
    for scale, word in [("standard", "Standard"), ("large", "Large")]:
        scales.append((word, {k: read_final(a.results / k / scale / "convergence.tsv")
                              for k, _ in VARIANTS}))
    name = "tab_mse_final.tex"
    (a.out / name).write_text(table(
        scales,
        r"Final MSE and macro iterations of HBC and HBC$_\text{WI}$, means "
        r"over 10 seeds, with the MSE relative to the lower of the two in "
        r"parentheses. Bold marks the better variant per dataset and column, "
        r"judged on unrounded values; both when equal.",
        "tab:mse_final"))
    print(f"  {a.out / name}")


if __name__ == "__main__":
    main()
