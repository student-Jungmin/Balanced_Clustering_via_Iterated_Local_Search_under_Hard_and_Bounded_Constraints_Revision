#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics
from collections import defaultdict
from pathlib import Path

VARIANTS = [
    ("centroids", "Stale centroids", "Per pair"),
    ("passcentroids", "Stale centroids", "Per pass"),
    ("pairs", "Fixed pair set", "Rebuilt mid-pass"),
]


def load(path: Path, marker: str | None):
    if not path.exists():
        return {}
    out = defaultdict(list)
    for r in csv.DictReader(path.open(), delimiter="\t"):
        tagged = "exact=" in r["config"]
        if (marker is None) != (not tagged):
            continue
        if marker is not None and f"exact={marker}" not in r["config"]:
            continue
        out[(r["dataset"], r["seed"])].append(
            (float(r["mse"]), float(r["time_s"])))
    return {k: (statistics.fmean(m for m, _ in v), statistics.fmean(t for _, t in v))
            for k, v in out.items()}


def compare(base, variant):
    import math
    import numpy as np
    import sys
    sys.path.insert(0, "tools")
    from stats.tests import logratio_test, tied
    keys = sorted(base.keys() & variant.keys())
    if not keys:
        return None
    by_ds = defaultdict(list)
    for k in keys:
        by_ds[k[0]].append(k)
    ds = sorted(by_ds)
    a_mse = np.array([statistics.fmean(variant[k][0] for k in by_ds[d]) for d in ds])
    b_mse = np.array([statistics.fmean(base[k][0] for k in by_ds[d]) for d in ds])
    a_t = [statistics.fmean(variant[k][1] for k in by_ds[d]) for d in ds]
    b_t = [statistics.fmean(base[k][1] for k in by_ds[d]) for d in ds]
    tie = tied(a_mse, b_mse)
    t = logratio_test(a_mse, b_mse)
    rel = np.where(tie, 0.0, (a_mse - b_mse) / b_mse)
    return {"datasets": len(ds), "runs": len(keys),
            "better": int(((a_mse < b_mse) & ~tie).sum()),
            "worse": int(((a_mse > b_mse) & ~tie).sum()),
            "median": float(np.median(rel)) * 100,
            "r": abs(t["effect_r"]), "p": t["p"],
            "time": math.exp(statistics.fmean(math.log(x / y) for x, y in zip(a_t, b_t)))}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/exactness"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    import sys
    sys.path.insert(0, "tools")
    from stats.tests import holm
    rows = []
    for scale, word in (("standard", "Standard"), ("large", "Large")):
        found = []
        for key, reviewer, description in VARIANTS:
            raw = a.results / scale / "raw_runs.tsv"
            result = compare(load(raw, None), load(raw, key))
            if result is not None:
                found.append((key, reviewer, description, result))
        if not found:
            continue
        qs = holm([r["p"] for *_, r in found])
        for (key, reviewer, description, r), q in zip(found, qs):
            p_text = r"$< 10^{-6}$" if q < 1e-6 else (
                "$1$" if q >= 0.9995 else f"${q:.3f}$")
            shown = f"{r['median']:+.3f}"
            if float(shown) == 0:
                shown = "0.000"
            rows.append(f"{word} & {reviewer} & {description} & "
                        f"{r['better']}/{r['datasets']} & {r['worse']}/{r['datasets']} & "
                        f"${shown}\\%$ & ${r['r']:.2f}$ & {p_text} & "
                        f"${r['time']:.2f}\\times$ \\\\")
    if not rows:
        raise SystemExit("no paired records - run experiments/exactness/run.sh first")
    name = "tab_exactness.tex"
    (a.out / name).write_text(f"""% generated by experiments/exactness/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{Cost of the two local-search approximations: each refreshed variant against the default, paired Wilcoxon tests over datasets (Section~\\ref{{sec:metric}}), Holm-corrected within each scale over the three variants. \\emph{{Better}}, \\emph{{Worse}}: datasets on which the variant's MSE is lower, higher; negative differences favor the variant. \\emph{{Time}}: geometric-mean runtime ratio to the default.}}
\\label{{tab:exactness}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{tabular}}{{@{{}}lllrrrrrr@{{}}}}
\\toprule
\\textbf{{Scale}} & \\textbf{{Reused quantity}} & \\textbf{{Refreshed variant}} & \\textbf{{Better}} & \\textbf{{Worse}} & \\textbf{{Median diff.}} & \\textbf{{Effect $r$}} & \\textbf{{$p$ (Holm)}} & \\textbf{{Time}} \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")
    print(f"  {a.out / name}")


if __name__ == "__main__":
    main()
