#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics
from collections import defaultdict
from pathlib import Path

LOCAL_SEARCH = [
    ("GetClusterPairs",     r"(a) \textbf{Get Pairs}"),
    ("GetProfits",          r"(b) \textbf{Get Profits}"),
    ("RankProfits",         r"(c) \textbf{Sort}"),
    ("FindSwapCount",       r"(d) \textbf{Bin Search}"),
    ("Swap",                r"(e) \textbf{Swap}"),
    ("UpdateClusterRadius", r"(f) \textbf{Update Rad.}"),
]
SUMMARY_LABELS = ["(a) Get Pairs", "(b) Get Profits", "(c) Sort",
                  "(d) Bin Search", "(e) Swap", "(f) Update Rad."]


def read_phases(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/runtime/run.sh first")
    acc: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    runs: dict[str, set] = defaultdict(set)
    per_run: dict[tuple, dict[str, float]] = defaultdict(lambda: defaultdict(float))
    with path.open() as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            key = (r["dataset"], r["seed"])
            runs[r["dataset"]].add(r["seed"])
            secs = float(r["seconds"])
            if r["part"] == "perturbation":
                per_run[key]["perturbation"] += secs
            elif r["part"] == "local_search":
                per_run[key][r["phase"]] += secs
    out: dict[str, dict[str, float]] = {}
    for dataset, rs in runs.items():
        cols = ["perturbation"] + [p for p, _ in LOCAL_SEARCH]
        out[dataset] = {c: statistics.fmean([per_run[(dataset, r)][c] for r in rs])
                        for c in cols}
    return out


def sci(x: float) -> str:
    if x <= 0:
        return r"0"
    s = f"{x:.2e}"
    mantissa, exponent = s.split("e")
    sign = "{-}" if exponent[0] == "-" else "{+}"
    return rf"{mantissa}\mathrm{{e}}{sign}{int(exponent[1:])}"


def shares(row: dict[str, float]) -> dict[str, float]:
    total = sum(row.values())
    return {k: (v / total if total > 0 else 0.0) for k, v in row.items()}


def detail_table(per_scale, caption, label) -> str:
    cols = ["perturbation"] + [p for p, _ in LOCAL_SEARCH]
    blocks = []
    for name, data in per_scale:
        rows = [rf"\multicolumn{{8}}{{l}}{{\textit{{{name} scale}}}} \\"]
        for dataset in sorted(data, key=str.lower):
            row = data[dataset]
            sh = shares(row)
            peak = max(cols, key=lambda c: sh[c])
            cells = []
            for c in cols:
                cell = rf"{sci(row[c])}\ ({sh[c]:.2f})"
                cells.append(rf"$\boldsymbol{{{cell}}}$" if c == peak else f"${cell}$")
            rows.append(rf"\quad {dataset} & " + " & ".join(cells) + r" \\")
        blocks.append("\n".join(rows))
    body = "\n\\midrule\n".join(blocks)
    header = " & ".join(lbl for _, lbl in LOCAL_SEARCH)
    return f"""% generated by experiments/runtime/tables.py -- do not edit
\\begin{{sidewaystable*}}[!t]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\resizebox{{\\ifdim\\width>\\textwidth\\textwidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{0.9}}
\\begin{{tabular}}{{l l c c c c c c}}
\\toprule
\\multirow{{2}}{{*}}{{\\textbf{{Dataset}}}} & \\multirow{{2}}{{*}}{{\\textbf{{Perturbation}}}} & \\multicolumn{{6}}{{c}}{{\\textbf{{Local Search Components}}}} \\\\
\\cmidrule(lr){{3-8}}
 & & {header} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
}}
\\end{{sidewaystable*}}
"""


def summary_table(per_scale, caption, label) -> str:
    def cell(vals, bold=False):
        mean, sd = statistics.fmean(vals), statistics.stdev(vals)
        if mean < 0.01:
            return r"$< 0.01$"
        body = rf"{mean:.2f} \pm {sd:.2f}"
        return rf"$\mathbf{{{body}}}$" if bold else f"${body}$"

    shared = [[shares(row) for row in data.values()] for _, data in per_scale]

    def mean_of(sh, getter):
        return statistics.fmean(getter(s) for s in sh)

    def line(name, getter, bold_in):
        cs = " & ".join(cell([getter(s) for s in sh], b)
                        for sh, b in zip(shared, bold_in))
        return rf"{name} & {cs} \\"

    pert = lambda s: s["perturbation"]
    ls = lambda s: sum(s[p] for p, _ in LOCAL_SEARCH)
    ls_wins = [mean_of(sh, ls) >= mean_of(sh, pert) for sh in shared]
    peak = [max(LOCAL_SEARCH, key=lambda pl: mean_of(sh, lambda s, p=pl[0]: s[p]))[0]
            for sh in shared]

    rows = [line(r"\textbf{Perturbation}", pert, [not w for w in ls_wins]),
            r"\addlinespace",
            line(r"\textbf{Local Search (Total)}", ls, ls_wins)]
    for (phase, _), label_text in zip(LOCAL_SEARCH, SUMMARY_LABELS):
        rows.append(line(rf"\quad {label_text}", lambda sh, p=phase: sh[p],
                         [p == phase for p in peak]))
    body = "\n".join(rows)
    header = " & ".join(rf"\textbf{{{n}}}" for n, _ in per_scale)
    return f"""% generated by experiments/runtime/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\begin{{tabular}}{{l{'c' * len(per_scale)}}}
\\toprule
\\multirow{{2}}{{*}}{{\\textbf{{Algorithmic Component}}}} & \\multicolumn{{{len(per_scale)}}}{{c}}{{\\textbf{{Mean Runtime Ratio}} $\\pm$ \\textbf{{Std}}}} \\\\
\\cmidrule(lr){{2-{1 + len(per_scale)}}}
 & {header} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/runtime"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    summaries = []
    for scale, word in [("standard", "Standard"), ("large", "Large")]:
        summaries.append((word, read_phases(args.results / scale / "phases.tsv")))

    name = "tab_detailed_time_breakdown.tex"
    (args.out / name).write_text(detail_table(
        summaries,
        r"Runtime (s) of the perturbation and each local-search component of "
        r"HBC$_\text{NA}$, with the share of the total in parentheses. Bold "
        r"marks the largest share per row.",
        "tab:detailed_time_breakdown"))
    print(f"  {args.out / name}")

    name = "tab_runtime_summary.tex"
    (args.out / name).write_text(summary_table(
        summaries,
        r"Runtime share per component of the unoptimized baseline "
        r"HBC$_\text{NA}$, mean $\pm$ standard deviation over datasets. Bold "
        r"marks the larger stage and the largest local-search component.",
        "tab:runtime_summary"))
    print(f"  {args.out / name}")


if __name__ == "__main__":
    main()
