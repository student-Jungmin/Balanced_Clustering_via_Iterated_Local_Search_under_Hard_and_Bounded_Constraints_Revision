#!/usr/bin/env python3
from __future__ import annotations
import argparse, statistics
from pathlib import Path

import pandas as pd

import measure
from measure import ARMS, BASE, SCALES, VARIANTS, tests


LABEL = {"better": "Better", "better_stall3": "Better, stall 3",
         "better_stall10": "Better, stall 10"}


def per_scale(results: Path):
    out = {}
    for scale, _ in SCALES:
        rows = []
        for f in sorted((results / scale).glob("raw_*.tsv")):
            for dataset, arms in measure.read(f).items():
                for arm, runs in arms.items():
                    for mse, seconds, seed in runs:
                        rows.append(dict(algorithm=arm, dataset=dataset, seed=seed,
                                         mse=mse, time_s=seconds))
        if rows:
            out[scale] = pd.DataFrame(rows)
    return out


LOG: list = []


def rows(frames):
    body = []
    for scale, scale_label in SCALES:
        df = frames.get(scale)
        if df is None:
            continue
        if body:
            body.append(r"\midrule")
        body.append(rf"\multicolumn{{7}}{{l}}{{\textit{{{scale_label.capitalize()}}}}} \\")
        for k, (metric, what) in enumerate((("mse", "MSE"), ("time_s", "Time"))):
            if k:
                body.append(r"\addlinespace")
            found = []
            for v in VARIANTS:
                sub = df[df["algorithm"].isin([v, BASE])]
                if v not in set(sub["algorithm"]):
                    continue
                r = tests.compare(sub, ours=BASE, metric=metric).iloc[0]
                found.append((v, r))
            for (v, r), q in zip(found, tests.holm([float(r["p"]) for _, r in found])):
                med = float(r["median_rel_diff"])
                shown = f"{med * 100:+.2f}"
                favors = "--" if float(shown) == 0 else ("Random Walk" if med < 0 else "Better")
                if float(shown) == 0:
                    shown = "0.00"
                body.append(
                    rf"\quad {LABEL[v]} & {what} & {int(r['ours_better'])}/{int(r['pairs'])} & "
                    rf"${shown}\%$ & ${abs(float(r['effect_r'])):.2f}$ & "
                    rf"${measure.fmt_p(q)}$ & {favors} \\")
                LOG.append((scale, what, v, r.get("zero_pairs"), r.get("p_method"),
                            len(found), float(r["p"]), q, abs(float(r["effect_r"]))))
    return body


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/acceptance"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    by_scale, _, stats, counts = measure.load(a.results)
    body = rows(per_scale(a.results))
    if not body:
        raise SystemExit("no paired records - run experiments/acceptance/run.sh first")

    name = "tab_acceptance.tex"
    (a.out / name).write_text(f"""% generated by experiments/acceptance/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{Acceptance criteria: Random Walk (RW, the default) against Better, alone and with a stall window of 3 or 10 iterations; paired Wilcoxon tests over datasets (Section~\\ref{{sec:metric}}), Holm-corrected within each scale and metric. On MSE all variants match RW's partition on 19 of 28 standard-scale and 10 of 11 large-scale datasets.}}
\\label{{tab:acceptance}}
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}llrrrrl@{{}}}}
\\toprule
\\textbf{{Against}} & \\textbf{{Metric}} & \\textbf{{RW wins}} & \\textbf{{Median diff.}} & \\textbf{{Effect $r$}} & \\textbf{{$p$ (Holm)}} & \\textbf{{Favors}} \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")
    summary = measure.write_summary(by_scale, stats, a.results / "summary.tsv")
    print(f"  {a.out / name}\n  {summary}")
    with open(a.out / "tab_acceptance.log.tsv", "w") as f:
        f.write("scale\tmetric\tvariant\tzero_pairs\tp_method\tholm_family\tp_raw\tp_holm\tr\n")
        for row in LOG:
            f.write("\t".join(str(x) for x in row) + "\n")
    for v in VARIANTS:
        c = counts[v]
        print(f"  {ARMS[v][0]:26s} {c['datasets']} datasets; lower MSE on "
              f"{c['mse_better']}, lower runtime on {c['time_better']}")


if __name__ == "__main__":
    main()
