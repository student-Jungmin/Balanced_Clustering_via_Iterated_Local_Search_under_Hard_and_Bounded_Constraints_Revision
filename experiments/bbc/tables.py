#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics, sys
from collections import defaultdict
from pathlib import Path

RHOS = ["0.01", "0.03", "0.05", "0.1", "0.25", "0.5", "1"]
OURS, THEIRS = "BBC", "TBC"


def family(algorithm: str) -> str:
    if algorithm.startswith(("BBC", "HBC")):
        return OURS
    if algorithm.startswith("TBC"):
        return THEIRS if algorithm.endswith("_repaired") else ""
    return ""


def read(path: Path, rhos=None):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/bbc/run.sh first")
    keep = RHOS if rhos is None else rhos
    acc = defaultdict(lambda: defaultdict(list))
    infeasible = defaultdict(int)
    for r in csv.DictReader(path.open(), delimiter="\t"):
        fam = family(r["algorithm"])
        rho = f'{float(r["rho"]):g}'
        if not fam or (keep and rho not in keep):
            continue
        if r["feasible"] != "1":
            raise SystemExit(f"{r['algorithm']} {r['dataset']} rho={rho} seed={r['seed']}: "
                             "outside max - min <= tau_eff")
        acc[r["dataset"]][(fam, rho)].append(
            (float(r["mse"]), float(r["time_s"]), float(r["tau"])))
    def sd(xs):
        xs = list(xs)
        return statistics.stdev(xs) if len(xs) > 1 else 0.0
    data = {d: {k: (statistics.fmean(m for m, _, _ in v),
                    statistics.fmean(t for _, t, _ in v),
                    statistics.fmean(x for _, _, x in v),
                    sd(m for m, _, _ in v),
                    sd(t for _, t, _ in v))
                for k, v in per.items()}
            for d, per in acc.items()}
    return data, infeasible


def sci(x: float) -> str:
    if x == 0:
        return "0"
    if 1e-2 <= abs(x) < 1e3:
        return f"{x:.2f}"
    mantissa, exponent = f"{x:.2e}".split("e")
    sign = "{-}" if exponent[0] == "-" else "{+}"
    return rf"{mantissa}\mathrm{{e}}{sign}{int(exponent[1:])}"


def table(data, datasets, caption, label, continued=False, rhos=None) -> str:
    rhos = rhos or RHOS
    rows = []
    for dataset in datasets:
        per = data[dataset]
        line = {"MSE": [], "Time": []}
        for rho in rhos:
            for fam in (THEIRS, OURS):
                cell = per.get((fam, rho))
                for metric, index in (("MSE", 0), ("Time", 1)):
                    if cell is None:
                        line[metric].append("--")
                    else:
                        other = per.get((THEIRS if fam == OURS else OURS, rho))
                        best = min(cell[index], other[index]) if other else cell[index]
                        body = f"${sci(cell[index])} \\pm {sci(cell[index + 3])}$"
                        line[metric].append(
                            rf"{{\boldmath {body}}}" if cell[index] <= best * (1 + 1e-9)
                            else body)
        rows.append(rf"\multirow{{2}}{{*}}{{{dataset}}} & MSE & "
                    + " & ".join(line["MSE"]) + r" \\")
        rows.append(" & Time & " + " & ".join(line["Time"]) + r" \\")
        rows.append(r"\addlinespace")
    body = "\n".join(rows[:-1])
    groups = " & ".join(rf"\multicolumn{{2}}{{c}}{{$\bm{{\rho = {r}}}$}}" for r in rhos)
    cmid = " ".join(rf"\cmidrule(lr){{{3+2*i}-{4+2*i}}}" for i in range(len(rhos)))
    heads = " & ".join(rf"\textbf{{{THEIRS}}} & \textbf{{{OURS}}}" for _ in rhos)
    counter = "\\addtocounter{table}{-1}\n" if continued else ""
    return f"""% generated by experiments/bbc/tables.py -- do not edit
{counter}\\begin{{sidewaystable}}[p]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\resizebox{{\\ifdim\\width>\\textwidth\\textwidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{0.9}}
\\begin{{tabular}}{{ll{'cc' * len(rhos)}}}
\\toprule
  & & {groups} \\\\
{cmid}
\\textbf{{Dataset}} & \\textbf{{Metric}} & {heads} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
}}
\\end{{sidewaystable}}
"""


def nk_of(path: Path):
    out = {}
    for r in csv.DictReader(path.open(), delimiter="\t"):
        out[r["dataset"]] = (int(r["n"]), int(r["k"]))
    return out


def paired(path: Path):
    sys.path.insert(0, "tools")
    import pandas as pd
    from stats.tests import compare, holm
    df = pd.read_csv(path, sep="\t")
    df["rho"] = df["rho"].astype(float)
    raw = {}
    for rho in sorted(r for r in df["rho"].unique() if f"{r:g}" in RHOS):
        d = df[df["rho"] == rho]
        if "BBC" not in set(d["algorithm"]):
            continue
        raw[f"{rho:g}"] = {}
        for metric in ("mse", "time_s"):
            row = compare(d, ours="BBC", metric=metric).iloc[0]
            raw[f"{rho:g}"][metric] = [int(row["ours_better"]), int(row["pairs"]),
                                      row["median_rel_diff"], row["effect_r"],
                                      float(row["p"]), int(row["zero_pairs"]),
                                      row["p_method"], float(row["p"])]
    for metric in ("mse", "time_s"):
        keys = list(raw)
        for k, q in zip(keys, holm([raw[k][metric][4] for k in keys])):
            raw[k][metric][4] = q
    return raw


def sweep_table(per_scale, caption, label) -> str:
    def p_text(p):
        if p < 1e-6:
            return r"$< 10^{-6}$"
        mantissa, exponent = f"{p:.2e}".split("e")
        return rf"${mantissa} \times 10^{{{int(exponent)}}}$"

    def scale_rows(data, tests):
        blocks = []
        for metric, name in (("mse", "MSE"), ("time_s", "Time")):
            rows = []
            for rho in sorted(tests, key=float):
                from fractions import Fraction
                from math import floor
                taus = [floor(Fraction(rho) * nk[d][0] / nk[d][1]) for d, per in data.items()
                        if per.get((OURS, rho)) and per.get((THEIRS, rho))]
                if not taus:
                    continue
                wins, n, med, eff, q = tests[rho][metric][:5]
                shown = f"{med * 100:+.2f}"
                fav = "--" if float(shown) == 0 else ("BBC" if med < 0 else "TBC")
                if float(shown) == 0:
                    shown = "0.00"
                rows.append(
                    f"\\quad ${float(rho):g}$ & {statistics.fmean(taus):.1f} & "
                    f"{name} & {wins}/{n} & ${shown}$ & "
                    f"${abs(eff):.2f}$ & {p_text(q)} & {fav}" + r" \\")
            blocks.append("\n".join(rows))
        return "\n\\addlinespace\n".join(blocks)

    blocks = []
    for name, data, tests, nk in per_scale:
        blocks.append(rf"\multicolumn{{8}}{{l}}{{\textit{{{name} scale}}}} \\"
                      + "\n" + scale_rows(data, tests))
    body = "\n\\midrule\n".join(blocks)
    return f"""% generated by experiments/bbc/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrlrrrrl@{{}}}}
\\toprule
$\\bm{{\\rho}}$ & \\textbf{{Mean $\\tau$}} & \\textbf{{Metric}} & \\textbf{{BBC wins}} & \\textbf{{Median rel. diff. (\\%)}} & \\textbf{{Effect $r$}} & \\textbf{{$p$ (Holm)}} & \\textbf{{Favors}} \\\\
\\midrule
{{body}}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""".replace("{body}", body)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/bbc"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    blocks = []
    for label, scale in (("Standard", "standard"), ("Large", "large")):
        raw = a.results / scale / "raw_runs.tsv"
        if not raw.exists():
            print(f"  note: {raw} not there yet; {label} block omitted")
            continue
        blocks.append((label, read(raw, rhos=())[0], paired(raw), nk_of(raw)))
    if not blocks:
        raise SystemExit("no BBC sweep has finished yet")
    name = "tab_rho_sweep.tex"
    (a.out / name).write_text(sweep_table(
        blocks,
        r"BBC against TBC over the relative tolerance $\rho$: paired Wilcoxon "
        r"tests over datasets (Section~\ref{sec:metric}), Holm-corrected within "
        r"each scale and metric over the seven $\rho$. Both use $\tau_{\mathrm{eff}} "
        r"= \lfloor \rho N/K \rfloor$, raised to $1$ where $K$ does not divide "
        r"$N$; \emph{Mean $\tau$} averages $\lfloor \rho N/K \rfloor$ over "
        r"datasets. Negative differences favor BBC.",
        "tab:rho_sweep"))
    print(f"  {a.out / name}")
    with open(a.out / "tab_rho_sweep.log.tsv", "w") as f:
        f.write("scale\trho\tmetric\tzero_pairs\tp_method\tholm_family\tp_raw\tp_holm\tr\n")
        for label, _, tests, _ in blocks:
            for rho, m in tests.items():
                for metric, v in m.items():
                    f.write(f"{label}\t{rho}\t{metric}\t{v[5]}\t{v[6]}\t{len(tests)}\t{v[7]}\t{v[4]}\t{abs(v[3])}\n")

    LO, HI = ["0.01", "0.03", "0.05", "0.1"], ["0.25", "0.5", "1"]
    CAP = ("MSE and runtime (s) of TBC and BBC on the {scale} datasets for "
           r"{span}, mean $\pm$ standard deviation over 10 seeds, with "
           r"$\tau_{{\mathrm{{eff}}}} = \lfloor \rho N/K \rfloor$ raised to $1$ "
           r"where $K$ does not divide $N$. Bold marks the better of each pair.")
    SPAN = {"lo": r"$\rho \le 0.1$", "hi": r"$\rho \ge 0.25$"}

    def floats(data, names, label, rhos, cap, split):
        if not split:
            return table(data, names, cap, label, rhos=rhos)
        half = (len(names) + 1) // 2
        rest = table(data, names[half:], "(continued)", "", continued=True, rhos=rhos)
        rest = rest.replace("\\label{}\n", "")
        return table(data, names[:half], cap, label, rhos=rhos) + rest.split("\n", 1)[1]

    for scale, stem, label, split in (("standard", "tab_bbc_results", "tab:bbc_results", True),
                                      ("large", "tab_bbc_results_large", "tab:bbc_results_large", False)):
        raw = a.results / scale / "raw_runs.tsv"
        if not raw.exists():
            continue
        data, _ = read(raw)
        names = sorted(data, key=str.lower)
        txt = floats(data, names, label, LO, CAP.format(scale=f"{scale}-scale", span=SPAN["lo"]), split)
        txt += "\n" + floats(data, names, label + "_hi", HI,
                             CAP.format(scale=f"{scale}-scale", span=SPAN["hi"]), split).split("\n", 1)[1]
        (a.out / f"{stem}.tex").write_text(txt)
        print(f"  {a.out / stem}.tex  ({len(data)} datasets)")


if __name__ == "__main__":
    main()
