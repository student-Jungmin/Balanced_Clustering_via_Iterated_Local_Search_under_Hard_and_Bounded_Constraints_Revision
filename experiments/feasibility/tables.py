#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, "tools")
from methods import rank as table1_rank

LABEL = {"MABMSSC": r"MA-BMSSC$\times$1",
         "MABMSSCx100": r"MA-BMSSC$\times$100",
         "LIMAx1": r"LIMA$\times$1",
         "LIMAx100": r"LIMA$\times$100",
         "SOBMSSC": "SO-BMSSC",
         "BKMPP": "BKM++"}


def variant(algorithm: str):
    if not algorithm.startswith("TBC"):
        return None, None
    base = algorithm.removesuffix("_repaired")
    digits = base[3:]
    if digits and not digits.isdigit():
        return None, None
    return ("repaired" if algorithm.endswith("_repaired") else "published",
            int(digits) / 100 if digits else 0.0)


def label(algorithm: str) -> str:
    if algorithm in LABEL:
        return LABEL[algorithm]
    kind, rho = variant(algorithm)
    if kind is None:
        return algorithm
    return rf"TBC ({kind}, $\rho$={rho:g})"


def order(algorithm: str):
    kind, rho = variant(algorithm)
    if kind is None:
        return (0, table1_rank(algorithm), "", 0.0)
    return (1, (), kind, rho)


def tau_eff(n: int, k: int, rho: float) -> int:
    from fractions import Fraction
    from math import floor
    return max(floor(Fraction(f"{rho:g}") * n / k), 1 if n % k else 0)


GRID = (0.01, 0.03, 0.05, 0.1, 0.25, 0.5, 1.0)
HARD = ["RKM", "BKMPP", "BKM", "LIMAx1", "LIMAx100", "MABMSSC", "MABMSSCx100",
        "SOBMSSC", "TBC_repaired", "HBC"]


def collect(paths, keep, key):
    stats = defaultdict(lambda: {"runs": 0, "within": 0, "overrun": 0, "rel": 0.0})
    for path in paths:
        if not path.exists():
            continue
        for r in csv.DictReader(path.open(), delimiter="\t"):
            if not keep(r):
                continue
            n, k, rho = int(r["n"]), int(r["k"]), float(r["rho"])
            over = int(r["max_size"]) - int(r["min_size"]) - tau_eff(n, k, rho)
            s = stats[key(r)]
            s["runs"] += 1
            s["within"] += over <= 0
            s["overrun"] = max(s["overrun"], over)
            s["rel"] = max(s["rel"], over / (n / k))
    return stats


def row(name, s) -> str:
    share = 100 * s["within"] / s["runs"]
    cell = rf"{share:.1f}\%"
    if share >= 100:
        cell = rf"\textbf{{{cell}}}"
    over = str(s["overrun"]) if s["overrun"] > 0 else "--"
    return f"{name} & {s['runs']} & {cell} & {over} \\\\"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    scales = ("standard", "large")
    on_grid = lambda r: any(abs(float(r["rho"]) - g) < 1e-9 for g in GRID)

    hard = collect([Path(f"results/benchmark/{s}/raw_runs.tsv") for s in scales],
                   lambda r: r["algorithm"] in HARD, lambda r: r["algorithm"])
    bounded = collect([Path(f"results/bbc/{s}/raw_runs.tsv") for s in scales],
                      on_grid,
                      lambda r: ("BBC" if r["algorithm"] in ("BBC", "HBC") else "TBC",
                                 float(r["rho"])))
    published = collect([Path(f"results/feasibility/{s}/raw_runs.tsv") for s in scales],
                        lambda r: float(r["rho"]) == 0 or on_grid(r),
                        lambda r: float(r["rho"]))
    if not hard:
        raise SystemExit("no raw records found - run a sweep first")
    a.out.mkdir(parents=True, exist_ok=True)

    names = dict(LABEL, TBC_repaired="TBC", HBC="HBC")
    rows = [r"\multicolumn{4}{l}{\textit{Hard balance} ($\rho = 0$)} \\"]
    rows += [row(names.get(x, x), hard[x]) for x in sorted(hard, key=table1_rank)]
    rows += [r"\midrule", r"\multicolumn{4}{l}{\textit{Bounded balance}} \\"]
    for rho in GRID:
        for fam in ("BBC", "TBC"):
            if (fam, rho) in bounded:
                rows.append(row(rf"{fam} ($\rho$={rho:g})", bounded[(fam, rho)]))
    if published:
        rows += [r"\midrule", r"\multicolumn{4}{l}{\textit{TBC as distributed}} \\"]
        rows += [row(rf"TBC ($\rho$={rho:g})", published[rho]) for rho in sorted(published)]
    body = "\n".join(rows)
    name = "tab_feasibility.tex"
    (a.out / name).write_text(f"""% generated by experiments/feasibility/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{Constraint satisfaction, scored for every method by the spread bound
$\\max_i |C_i| - \\min_i |C_i| \\le \\tau_{{\\mathrm{{eff}}}}$, with
$\\tau_{{\\mathrm{{eff}}}} = \\lfloor \\rho N/K \\rfloor$, raised to $1$ where $K$ does not divide $N$,
at the method's own $\\rho$. \\emph{{Within tolerance}} is the share of runs that
satisfy it; \\emph{{largest overrun}} is the most points by which any run's spread
exceeded $\\tau_{{\\mathrm{{eff}}}}$, a dash meaning none did. The last block is TBC as
distributed, which bounds the cluster capacity rather than the spread; the
comparisons use the repaired mode.}}
\\label{{tab:feasibility}}
\\small
\\begin{{tabular}}{{lrrr}}
\\toprule
\\textbf{{Algorithm}} & \\textbf{{Runs}} & \\textbf{{Within tolerance}} & \\textbf{{Largest overrun}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")
    print(f"  {a.out / name}")

    if published:
        def prow(rho, st):
            share = 100 * st["within"] / st["runs"]
            exc = f"{100 * st['rel']:.1f}" if st["overrun"] > 0 else "--"
            return f"${rho:g}$ & {st['runs']} & {share:.1f} & {exc} \\\\"
        body = "\n".join(prow(rho, published[rho]) for rho in sorted(published))
        name = "tab_feasibility_published.tex"
        (a.out / name).write_text(
            "% generated by experiments/feasibility/tables.py -- do not edit\n"
            "\\begin{table}[htbp]\n\\centering\n"
            "\\caption{Constraint satisfaction of TBC as distributed, scored by the spread bound\n"
            "$\\max_i |C_i| - \\min_i |C_i| \\le \\tau$ at each $\\rho$ over the 39 datasets and 10 seeds.\n"
            "\\emph{Feasible} is the share of runs that satisfy it; \\emph{Max.\\ excess} is the largest\n"
            "amount by which a run's spread exceeded $\\tau$, as a percentage of the mean cluster size $N/K$.}\n"
            "\\label{tab:feasibility_published}\n\\small\n\\begin{tabular}{lrrr}\n\\toprule\n"
            "$\\bm{\\rho}$ & \\textbf{Runs} & \\textbf{Feasible (\\%)} & \\textbf{Max.\\ excess (\\% of $\\bm{N/K}$)} \\\\\n"
            "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
        print(f"  {a.out / name}")

    fixed = {0.0: hard["TBC_repaired"]} if "TBC_repaired" in hard else {}
    fixed.update({rho: bounded[("TBC", rho)] for rho in GRID if ("TBC", rho) in bounded})
    if fixed:
        body = "\n".join(row(rf"${rho:g}$", fixed[rho]) for rho in sorted(fixed))
        name = "tab_feasibility_repaired.tex"
        (a.out / name).write_text(f"""% generated by experiments/feasibility/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{Constraint satisfaction of TBC as modified to enforce its balance constraint,
scored as in Table~\\ref{{tab:feasibility_published}}.}}
\\label{{tab:feasibility_repaired}}
\\small
\\begin{{tabular}}{{lrrr}}
\\toprule
$\\bm{{\\rho}}$ & \\textbf{{Runs}} & \\textbf{{Within tolerance}} & \\textbf{{Largest overrun}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")
        print(f"  {a.out / name}")


if __name__ == "__main__":
    main()
