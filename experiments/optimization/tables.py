#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics, sys
from collections import defaultdict
from pathlib import Path


def read_runs(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/optimization/run.sh first")
    out = {}
    for r in csv.DictReader(path.open(), delimiter="\t"):
        out[(r["dataset"], r["seed"])] = r
    return out


def compare(before: dict, after: dict):
    broken, per_dataset, mse_delta = [], defaultdict(lambda: ([], [])), []
    for key in sorted(before.keys() & after.keys()):
        b, a = before[key], after[key]
        for field in ("mse", "sse", "iters", "min_size", "max_size", "feasible"):
            if b[field] != a[field]:
                broken.append((key, field, b[field], a[field]))
        mb, ma = float(b["mse"]), float(a["mse"])
        if mb > 0:
            mse_delta.append((ma - mb) / mb)
        per_dataset[key[0]][0].append(float(b["time_s"]))
        per_dataset[key[0]][1].append(float(a["time_s"]))
    return per_dataset, broken, mse_delta


def table(per_scale, caption, label) -> str:
    blocks = []
    for name, per_dataset in per_scale:
        rows = [rf"\multicolumn{{4}}{{l}}{{\textit{{{name} scale}}}} \\"]
        speedups = []
        for d in sorted(per_dataset, key=str.lower):
            bs, as_ = per_dataset[d]
            b, a = statistics.fmean(bs), statistics.fmean(as_)
            sp = b / a if a > 0 else float("nan")
            speedups.append(sp)
            rows.append(rf"\quad {d} & {b:.3f} & {a:.3f} & {sp:.2f}$\times$ \\")
        gm = statistics.geometric_mean(speedups)
        rows.append(r"\addlinespace")
        rows.append(rf"\quad \textbf{{Geometric mean}} & & & "
                    rf"$\mathbf{{{gm:.2f}\times}}$ \\")
        blocks.append("\n".join(rows))
    body = "\n\\midrule\n".join(blocks)
    return f"""% generated by experiments/optimization/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\renewcommand{{\\arraystretch}}{{0.85}}
\\begin{{tabular}}{{l r r r}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Full sort (s)}} & \\textbf{{Prefix (s)}} & \\textbf{{Speedup}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/optimization"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    failed = False
    blocks = []
    for scale, word in [("standard", "standard-scale"),
                        ("large", "large-scale")]:
        before = read_runs(a.results / "before" / scale / "raw_runs.tsv")
        after = read_runs(a.results / "after" / scale / "raw_runs.tsv")
        per_dataset, broken, mse_delta = compare(before, after)
        n = sum(len(v[0]) for v in per_dataset.values())
        if broken:
            failed = True
            print(f"  [{scale}] {len(broken)} paired runs changed the partition:",
                  file=sys.stderr)
            for key, field, b, x in broken[:5]:
                print(f"    {key} {field}: {b} -> {x}", file=sys.stderr)
        else:
            worse = sum(1 for d in mse_delta if d > 1e-12)
            worst = max((abs(d) for d in mse_delta), default=0.0)
            print(f"  [{scale}] {n} paired runs, partitions identical; "
                  f"MSE moved by at most {100*worst:.4f}%, worse on {worse}")
        blocks.append((word.replace("-scale", "").capitalize(), per_dataset))

    name = "tab_prefix_ranking_speedup.tex"
    (a.out / name).write_text(table(
        blocks,
        r"Mean runtime (s) of HBC sorting all profits or ranking only the "
        r"prefix the binary search reads; both return identical partitions. "
        r"Bold marks each scale's geometric-mean speedup.",
        "tab:prefix_ranking_speedup"))
    print(f"  {a.out / name}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
