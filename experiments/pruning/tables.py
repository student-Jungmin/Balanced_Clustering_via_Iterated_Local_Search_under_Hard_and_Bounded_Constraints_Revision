#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, math, statistics
from collections import defaultdict
from pathlib import Path

VARIANTS = [
    ("HBC_NA", r"(a) $\text{HBC}_\text{NA}$", "Unoptimized baseline (Full convergence)"),
    ("HBC_NO", r"(b) $\text{HBC}_\text{NO}$", "Truncated baseline (Single pass)"),
    ("HBC_WG", r"(c) $\text{HBC}_\text{WG}$", "Proposed without Geometric Pruning"),
    ("HBC_WI", r"(d) $\text{HBC}_\text{WI}$", "Proposed without Synchronization"),
    ("HBC",    r"(e) HBC",                      r"\textbf{Proposed Framework (Full)}"),
]
BASELINE = "HBC_NA"


def read_pairs(root: Path, variant: str, scale: str) -> dict[str, float]:
    path = root / variant / scale / "pairs.tsv"
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/pruning/run.sh first")
    per_run: dict[str, list[float]] = defaultdict(list)
    with path.open() as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            if row["stage"] == "after_c2":
                per_run[row["dataset"]].append(float(row["count"]))
    return {d: statistics.fmean(v) for d, v in per_run.items()}


def fmt_count(x: float) -> str:
    if x >= 1e5:
        return f"{x:.3e}"
    s = f"{x:.1f}"
    return s[:-2] if s.endswith(".0") else s


def summary_table(per_scale, caption, label) -> str:
    def cell(counts, key):
        ratios = [counts[key][d] / counts[BASELINE][d]
                  for d in counts[BASELINE] if counts[BASELINE][d] > 0]
        mean, sd = statistics.fmean(ratios), statistics.stdev(ratios)
        s = f"{mean:.2f} \\pm {sd:.3f}"
        return f"$\\mathbf{{{s}}}$" if key == "HBC" else f"${s}$"

    rows = []
    for key, name, description in VARIANTS:
        if key == "HBC":
            name = "(e) \\textbf{HBC}"
        cells = " & ".join(cell(c, key) for _, c in per_scale)
        rows.append(f"{name} & {description} & {cells} \\\\")
    body = "\n\\addlinespace\n".join(rows)
    heads = " & ".join(f"\\textbf{{{w}}}" for w, _ in per_scale)
    return f"""% generated by experiments/pruning/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\begin{{tabular}}{{ll{"c" * len(per_scale)}}}
\\toprule
\\textbf{{Variant}} & \\textbf{{Ablation Description}} & {heads} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def detail_table(per_scale, caption, label) -> str:
    header = " & ".join(f"\\textbf{{{n}}}" for _, n, _ in VARIANTS)

    def scale_rows(counts):
        datasets = sorted(counts[BASELINE], key=str.lower)
        rows = []
        for d in datasets:
            base = counts[BASELINE][d]
            cells, values = [], []
            for key, _, _ in VARIANTS:
                c = counts[key][d]
                values.append(c)
                ratio = c / base if base > 0 else float("nan")
                cells.append(f"{fmt_count(c)} ({ratio:.3f})")
            best = min(values)
            cells = [f"\\textbf{{{c}}}" if v == best else c
                     for c, v in zip(cells, values)]
            rows.append(rf"\quad {d} & " + " & ".join(cells) + r" \\")

        summary = []
        for key, _, _ in VARIANTS:
            ratios = [counts[key][d] / counts[BASELINE][d]
                      for d in datasets if counts[BASELINE][d] > 0]
            m, sd = statistics.fmean(ratios), statistics.stdev(ratios)
            summary.append(f"${m:.3f} \\pm {sd:.3f}$")
        rows.append(r"\addlinespace")
        rows.append(r"\quad \textbf{Mean Ratio $\pm$ Std (across datasets)} & "
                    + " & ".join(summary) + r" \\")
        return rows

    blocks = []
    for name, counts in per_scale:
        rows = [rf"\multicolumn{{6}}{{l}}{{\textit{{{name} scale}}}} \\"]
        rows += scale_rows(counts)
        blocks.append("\n".join(rows))
    body = "\n\\midrule\n".join(blocks)
    return f"""% generated by experiments/pruning/tables.py -- do not edit
\\begin{{sidewaystable*}}[p]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\resizebox{{\\ifdim\\width>\\textwidth\\textwidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{0.9}}
\\begin{{tabular}}{{l c c c c c}}
\\toprule
\\textbf{{Dataset}} & {header} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
}}
\\end{{sidewaystable*}}
"""


def limits_table(per_scale, caption, label) -> str:
    blocks = []
    for name, counts, shapes in per_scale:
        rows = [rf"\multicolumn{{5}}{{l}}{{\textit{{{name} scale}}}} \\"]
        for dataset in sorted(counts["HBC"], key=str.lower):
            total = counts["_total"][dataset]
            c1, c2 = counts["_c1"][dataset], counts["HBC"][dataset]
            d, k = shapes[dataset]
            keep = 100 * c1 / total if total else float("nan")
            final = 100 * c2 / total if total else float("nan")
            rows.append(rf"\quad {dataset} & {d} & {k} & {keep:.1f}\% & "
                        rf"{final:.1f}\% \\")
        blocks.append(chr(10).join(rows))
    body = (chr(10) + "\\midrule" + chr(10)).join(blocks)
    return f"""% generated by experiments/pruning/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\renewcommand{{\\arraystretch}}{{0.85}}
\\begin{{tabular}}{{lrrrr}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Dim.}} & \\textbf{{K}} & \\textbf{{Kept by C1}} & \\textbf{{Kept by C1+C2}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def read_phases(root: Path, variant: str, scale: str):
    from collections import defaultdict as dd
    per = dd(lambda: dd(float))
    path = root / variant / scale / "phases.tsv"
    if not path.exists():
        return {}
    for r in csv.DictReader(path.open(), delimiter="\t"):
        key = (r["dataset"], r["seed"])
        per[key][r["part"]] += float(r["seconds"])
        per[key]["_" + r["phase"]] += float(r["seconds"])
    return per


def removed_table(per_scale, caption, label) -> str:
    parts = [("perturbation", "Perturbation"),
             ("local_search", r"\textbf{Local search (total)}"),
             ("_GetProfits", r"\quad Get profits"),
             ("_RankProfits", r"\quad Sort"),
             ("_GetClusterPairs", r"\quad Get pairs")]

    def mean_speedup(before, after, part):
        assert set(before) == set(after), sorted(set(before) ^ set(after))[:4]
        per = defaultdict(lambda: [0.0, 0.0])
        for k in set(before) & set(after):
            if part is None:
                a = sum(v for q, v in before[k].items() if not q.startswith("_"))
                b = sum(v for q, v in after[k].items() if not q.startswith("_"))
            else:
                a, b = before[k].get(part, 0.0), after[k].get(part, 0.0)
            per[k[0]][0] += a
            per[k[0]][1] += b
        speedups = [a / b for a, b in per.values() if a > 0 and b > 0]
        dropped = len(per) - len(speedups)
        if dropped:
            print(f"    note: {part or 'total'} skips {dropped} dataset(s) "
                  f"with a zero time; {len(speedups)} of {len(per)} used")
        if len(speedups) < 2:
            return None
        gsd = math.exp(statistics.stdev(math.log(x) for x in speedups))
        return statistics.geometric_mean(speedups), gsd

    def cell(r, bold=False):
        if r is None:
            return "--"
        gm, gsd = r
        if bold:
            return rf"$\mathbf{{{gm:.2f}\times}}$ $\mathbf{{({gsd:.2f})}}$"
        return rf"${gm:.2f}\times$ $({gsd:.2f})$"

    rows = []
    for part, name in parts:
        rs = [mean_speedup(bef, aft, part) for _, bef, aft in per_scale]
        if all(r is None for r in rs):
            continue
        rows.append(f"{name} & " + " & ".join(cell(r, part == "local_search") for r in rs) + r" \\")
    rows.append(r"\midrule")
    rows.append(r"\textbf{Total} & " + " & ".join(
        cell(mean_speedup(bef, aft, None)) for _, bef, aft in per_scale) + r" \\")

    header = " & ".join(rf"\textbf{{{n}}}" for n, _, _ in per_scale)
    return f"""% generated by experiments/pruning/tables.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\begin{{tabular}}{{l{'r' * len(per_scale)}}}
\\toprule
\\textbf{{Component}} & {header} \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def read_stage(root: Path, variant: str, scale: str, stage: str) -> dict[str, float]:
    path = root / variant / scale / "pairs.tsv"
    per_run: dict[str, list[float]] = defaultdict(list)
    with path.open() as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            if row["stage"] == stage:
                per_run[row["dataset"]].append(float(row["count"]))
    return {d: statistics.fmean(v) for d, v in per_run.items()}


def read_shapes(root: Path, variant: str, scale: str) -> dict[str, tuple[int, int]]:
    path = root / variant / scale / "pairs.tsv"
    out = {}
    with path.open() as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            out[row["dataset"]] = (int(row["d"]), int(row["k"]))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/pruning"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    summaries = []
    details = []
    effects = []
    limits = []
    for scale, suffix, word in [("standard", "", "standard-scale"),
                                ("large", "_large", "large-scale")]:
        counts = {key: read_pairs(args.results, key, scale) for key, _, _ in VARIANTS}
        summaries.append((word.replace("-scale", "").capitalize(), counts))
        details.append((word.replace("-scale", "").capitalize(), counts))

        before = read_phases(args.results, BASELINE, scale)
        after = read_phases(args.results, "HBC", scale)
        if before and after:
            effects.append((word.replace("-scale", "").capitalize(), before, after))

        counts["_total"] = read_stage(args.results, "HBC", scale, "total")
        counts["_c1"] = read_stage(args.results, "HBC", scale, "after_c1")
        limits.append((word.replace("-scale", "").capitalize(), counts,
                       read_shapes(args.results, "HBC", scale)))

    import statistics
    from math import isnan
    keep_by_d, pairs = {"low": [], "high": []}, []
    for _, counts, shapes in limits:
        for dataset, c1 in counts["_c1"].items():
            total = counts["_total"][dataset]
            if not total:
                continue
            d, k = shapes[dataset]
            keep = 100 * c1 / total
            c2 = 100 * counts["HBC"][dataset] / total
            pairs.append((d, k, keep, c2))
            if d <= 5:
                keep_by_d["low"].append(keep)
            if d >= 30:
                keep_by_d["high"].append(keep)
    def spearman(xs, ys):
        from scipy.stats import rankdata
        rx, ry = rankdata(xs), rankdata(ys)
        mx, my = statistics.fmean(rx), statistics.fmean(ry)
        num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
        den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** 0.5
        return num / den if den else float("nan")
    tight = [(keep - c2) / keep * 100 for _, _, keep, c2 in pairs if keep >= 95]
    print(f"  Section 5 figures over {len(pairs)} datasets:")
    print(f"    C1 keeps a median {statistics.median(keep_by_d['low']):.1f}% of pairs at d <= 5 "
          f"({len(keep_by_d['low'])} datasets) and {statistics.median(keep_by_d['high']):.1f}% at d >= 30 "
          f"({len(keep_by_d['high'])} datasets)")
    print(f"    Spearman of C1-kept share with d: {spearman([p[0] for p in pairs], [p[2] for p in pairs]):+.3f}, "
          f"with K: {spearman([p[1] for p in pairs], [p[2] for p in pairs]):+.3f}")
    print(f"    where C1 keeps >= 95%, C2 then removes a median "
          f"{statistics.median(tight):.1f}% of those pairs ({len(tight)} datasets)")

    name = "tab_overlap_analysis.tex"
    (args.out / name).write_text(detail_table(
        details,
        r"Mean number of cluster pairs reaching the sorting step per variant, "
        r"with the ratio to HBC$_\text{NA}$ in parentheses. Bold marks the "
        r"smallest per row; \emph{Mean Ratio $\pm$ Std} is over datasets.",
        "tab:overlap_analysis"))
    print(f"  {args.out / name}")

    name = "tab_pruning_limits.tex"
    (args.out / name).write_text(limits_table(
        limits,
        r"Share of cluster pairs kept by C1, the bounding-sphere test, and by "
        r"C1 with C2, the maximum-profit-sum test.",
        "tab:pruning_limits"))
    print(f"  {args.out / name}")

    if effects:
        name = "tab_optimization_effect.tex"
        (args.out / name).write_text(removed_table(
            effects,
            r"Per-component speedup of HBC over the unoptimized baseline "
            r"HBC$_\text{NA}$: geometric mean over datasets (geometric standard "
            r"deviation). Bold marks the local-search total, whose parts follow.",
            "tab:optimization_effect"))
        print(f"  {args.out / name}")

    name = "tab_ablation_summary.tex"
    (args.out / name).write_text(summary_table(
        summaries,
        r"Cluster pairs evaluated by each variant relative to the unoptimized "
        r"baseline HBC$_\text{NA}$, mean $\pm$ standard deviation over "
        r"datasets. Bold marks our method.",
        "tab:ablation_summary"))
    print(f"  {args.out / name}")


if __name__ == "__main__":
    main()
