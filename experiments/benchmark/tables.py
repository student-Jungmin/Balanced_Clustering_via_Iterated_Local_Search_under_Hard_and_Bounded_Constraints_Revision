#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, re, statistics, sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, "tools")
from methods import sort as table1_order

ORDER = table1_order(["BKM", "BKMPP", "LIMAx1", "LIMAx100", "RKM",
                      "TBC_repaired", "SOBMSSC", "MABMSSC",
                      "MABMSSCx100", "HBC"])
WRAP = {
    "Image Segmentation": r"\makecell[l]{Image\\Segmentation}",
    "Letter Recognition": r"\makecell[l]{Letter\\Recognition}",
    "Multiple Features": r"\makecell[l]{Multiple\\Features}",
    "Sensorless Drive": r"\makecell[l]{Sensorless\\Drive}",
    "Synthetic Control": r"\makecell[l]{Synthetic\\Control}",
    "User Knowledge": r"\makecell[l]{User\\Knowledge}",
    "User Model": r"\makecell[l]{User\\Model}",
    "Vowel Recognition": r"\makecell[l]{Vowel\\Recognition}",
    "Breast Cancer": r"\makecell[l]{Breast\\Cancer}",
}


def dsname(name: str) -> str:
    return WRAP.get(name, name)


LABEL = {"MABMSSC": "MA-BMSSC$\\times 1$", "MABMSSCx100": "MA-BMSSC$\\times 100$",
         "LIMAx1": "LIMA$\\times 1$", "LIMAx100": "LIMA$\\times 100$",
         "SOBMSSC": "SO-BMSSC", "TBC_repaired": "TBC", "BKMPP": "BKM++"}
OURS = "HBC"

BBC_VARIANT = re.compile(r"^TBC([0-9]+)?(_repaired)?$")


def read(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/benchmark/run.sh first")
    acc = defaultdict(lambda: defaultdict(list))
    unlisted = set()
    for r in csv.DictReader(path.open(), delimiter="\t"):
        if r["algorithm"] not in ORDER:
            if not BBC_VARIANT.match(r["algorithm"]):
                unlisted.add(r["algorithm"])
            continue
        acc[r["dataset"]][r["algorithm"]].append(
            (float(r["mse"]), float(r["time_s"])))
    if unlisted:
        print(f"  warning: {path} holds records for {', '.join(sorted(unlisted))}"
              f", which are not in ORDER and have been dropped from the table",
              file=sys.stderr)
    return acc


def means(raw):
    return {d: {a: (statistics.fmean(m for m, _ in v),
                    statistics.fmean(t for _, t in v))
                for a, v in per.items()}
            for d, per in raw.items()}


def sci(x: float) -> str:
    if x == 0:
        return "0"
    if 1e-2 <= abs(x) < 1e3:
        return f"{x:.2f}"
    mantissa, exponent = f"{x:.2e}".split("e")
    sign = "{-}" if exponent[0] == "-" else "{+}"
    return rf"{mantissa}\mathrm{{e}}{sign}{int(exponent[1:])}"


def cell(value: float, best: float) -> str:
    body = rf"${sci(value)}\ ({value / best:.2f})$" if best > 0 else f"${sci(value)}$"
    return rf"{{\boldmath {body}}}" if value <= best * (1 + 1e-9) else body


def table(data, columns, denominator, metric, index, caption, label) -> str:
    rows, ratios = [], defaultdict(list)
    for dataset in sorted(data, key=str.lower):
        per = data[dataset]
        values = {a: per[a][index] for a in columns if a in per}
        pool = [per[a][index] for a in denominator if a in per]
        best = min(pool) if pool else 0.0
        cells = [cell(values[a], best) if a in values else "--" for a in columns]
        for a in columns:
            if a in values and best > 0:
                ratios[a].append(values[a] / best)
        rows.append(f"{dsname(dataset)} & " + " & ".join(cells) + r" \\")
    summary = [rf"${statistics.fmean(v):.2f} \pm {statistics.stdev(v):.2f}$"
               if (v := ratios[a]) else "--" for a in columns]
    body = "\n".join(rows + [r"\midrule",
                             r"\textbf{Average} & " + " & ".join(summary) + r" \\"])
    header = " & ".join(rf"\textbf{{{LABEL.get(a, a)}}}" for a in columns)
    return f"""% generated by experiments/benchmark/tables.py -- do not edit
\\begin{{table*}}[!t]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\resizebox{{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{1.0}}
\\begin{{tabular}}{{@{{}} l {'c ' * len(columns)}@{{}}}}
\\toprule
\\textbf{{Dataset}} & {header} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
}}
\\end{{table*}}
"""


GROUP_A = table1_order(["RKM", "TBC_repaired", "SOBMSSC", OURS])
GROUP_B = table1_order(["BKM", "BKMPP", "LIMAx1", "LIMAx100",
                        "MABMSSC", "MABMSSCx100", OURS])
FAMILIES = [("A", GROUP_A, ""), ("B", GROUP_B, "_b")]


SPREAD_CHUNK = 9


DATASETS_PER_FLOAT = 14


def spread_table(raw, columns, caption, label) -> str:
    def block(datasets, part):
        rows = []
        for dataset in datasets:
            per = raw[dataset]
            line = {}
            for metric, index in (("MSE", 0), ("Time", 1)):
                series = {a_: [v[index] for v in per[a_]]
                          for a_ in columns if a_ in per}
                best = min((statistics.fmean(v) for v in series.values()),
                           default=0.0)
                cells = []
                for a_ in columns:
                    if a_ not in series:
                        cells.append("--")
                        continue
                    m = statistics.fmean(series[a_])
                    sd = statistics.stdev(series[a_])
                    if sd <= abs(m) * 1e-12:
                        sd = 0.0
                    body = rf"${sci(m)} \pm {sci(sd)}$"
                    cells.append(rf"{{\boldmath {body}}}"
                                 if m <= best * (1 + 1e-9) else body)
                line[metric] = cells
            rows += [rf"\multirow{{2}}{{*}}{{{dsname(dataset)}}} & MSE & "
                     + " & ".join(line["MSE"]) + r" \\",
                     " & Time & " + " & ".join(line["Time"]) + r" \\",
                     r"\addlinespace"]
        header = " & ".join(rf"\textbf{{{LABEL.get(a_, a_)}}}" for a_ in columns)
        return f"""\\begin{{sidewaystable*}}[p]
\\centering
\\caption{{{caption if not part else '(continued)'}}}
{'' if part else chr(92) + 'label{' + label + '}'}
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\resizebox{{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}}{{!}}{{
\\renewcommand{{\\arraystretch}}{{1.0}}
\\begin{{tabular}}{{@{{}} l l {'c ' * len(columns)}@{{}}}}
\\toprule
\\textbf{{Dataset}} & \\textbf{{Metric}} & {header} \\\\
\\midrule
{chr(10).join(rows[:-1])}
\\bottomrule
\\end{{tabular}}
}}
\\end{{sidewaystable*}}"""

    datasets = sorted(raw, key=str.lower)
    parts = [datasets[i:i + DATASETS_PER_FLOAT]
             for i in range(0, len(datasets), DATASETS_PER_FLOAT)]
    out = ["% generated by experiments/benchmark/tables.py -- do not edit"]
    for i, ds in enumerate(parts):
        if i:
            out.append(r"\addtocounter{table}{-1}")
        out.append(block(ds, i))
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=Path("results/benchmark"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    for scale, suffix, word in [("standard", "", "standard-scale"),
                                ("large", "_large", "large-scale")]:
        raw = read(a.results / scale / "raw_runs.tsv")
        data = means(raw)
        present = {alg for per in data.values() for alg in per}
        columns = [a_ for a_ in ORDER if a_ in present]
        if OURS not in columns:
            raise SystemExit(f"no {OURS} records in {scale}")
        seeds = max(len(v) for per in raw.values() for v in per.values())
        families = [g for _, g, _ in FAMILIES
                    if len([c for c in g if c in present]) >= 2]
        n_tables = 2 * len(families)
        for family, group, tag in FAMILIES:
            cols = [c for c in group if c in present]
            if len(cols) < 2:
                continue

            for metric, index, unit, label in [
                    ("MSE", 0, "", "mse"), ("runtime", 1, " in seconds", "time")]:
                name = f"tab_hbc_{label}{tag}{suffix}.tex"
                (a.out / name).write_text(table(
                    data, cols, columns, metric, index,
                    f"{metric.upper() if metric == 'MSE' else metric.capitalize()}"
                    f"{unit} on {word} datasets, for "
                    f"{', '.join(LABEL.get(c, c) for c in cols[:-1])} and {OURS}. Each entry is "
                    f"the mean over {seeds} seeds and, in parentheses, its ratio "
                    f"to the lowest mean on that dataset; bold marks that "
                    f"lowest mean.",
                    f"tab:hbc_{label}{tag}{suffix}"))
                print(f"  {a.out / name}  ({len(data)} datasets, {family}, "
                      f"{metric}: {', '.join(cols)})")


        name = f"tab_per_dataset_sd{suffix}.tex"
        (a.out / name).write_text(spread_table(
            raw, columns,
            f"MSE and runtime (s) on the {word} datasets, mean $\\pm$ standard "
            f"deviation over {seeds} seeds. Bold marks the lowest mean per row.",
            f"tab:per_dataset_sd{suffix}"))
        print(f"    {a.out / name}  ({len(columns)} methods)")


if __name__ == "__main__":
    main()
