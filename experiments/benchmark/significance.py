#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, sys
from pathlib import Path

sys.path.insert(0, "tools")
from methods import rank as table1_rank

LABEL = {
    "TBC_repaired": "TBC",
    "TBC1_repaired": r"TBC ($\rho{=}0.01$)",
    "TBC3_repaired": r"TBC ($\rho{=}0.03$)",
    "TBC5_repaired": r"TBC ($\rho{=}0.05$)",
    "TBC1": r"TBC ($\rho{=}0.01$)",
    "TBC3": r"TBC ($\rho{=}0.03$)",
    "TBC5": r"TBC ($\rho{=}0.05$)",
    "SOBMSSC": "SO-BMSSC",
    "MABMSSC": "MA-BMSSC$\\times$1",
    "MABMSSCx100": "MA-BMSSC$\\times$100",
    "BKMPP": "BKM++",
    "LIMAx1": r"LIMA$\times$1",
    "LIMAx100": r"LIMA$\times$100",
}


def escape(name: str) -> str:
    return name.replace("\\", r"\textbackslash{}").replace("_", r"\_") \
               .replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")


UNCONSTRAINED = {"TBC", "TBC1", "TBC3", "TBC5"}

BOUNDED = {"TBC1_repaired", "TBC3_repaired", "TBC5_repaired",
           "TBC10_repaired", "TBC25_repaired", "TBC50_repaired",
           "TBC100_repaired"}


def rows(path: Path, metric: str, log=None):
    if not path.exists():
        raise SystemExit(f"missing {path} - run experiments/benchmark/run.sh first")
    kept = [r for r in csv.DictReader(path.open())
            if r["baseline"] not in UNCONSTRAINED and r["baseline"] not in BOUNDED]
    kept.sort(key=lambda r: table1_rank(r["baseline"]))
    sys.path.insert(0, "tools")
    from stats.tests import holm
    qs = holm([float(r["p"]) for r in kept])
    out = []
    for r, p in zip(kept, qs):
        name = LABEL.get(r["baseline"]) or escape(r["baseline"])
        median = float(r["median_rel_diff"]) * 100
        effect = float(r["effect_r"])
        if p < 1e-6:
            p_text = r"$< 10^{-6}$"
        else:
            mantissa, exponent = f"{p:.2e}".split("e")
            p_text = rf"${mantissa} \times 10^{{{int(exponent)}}}$"
        shown = f"{median:+.2f}"
        better = "--" if float(shown) == 0 else ("HBC" if median < 0 else "baseline")
        if shown in ("+0.00", "-0.00"):
            shown = "0.00"
        out.append(f"\\quad {name} & {metric} & {r['ours_better']}/{r['pairs']} & "
                   f"${shown}\\%$ & ${abs(effect):.2f}$ & {p_text} & {better} \\\\")
        if log is not None:
            log.append((metric, r["baseline"], r.get("zero_pairs", "?"),
                        r.get("p_method", "?"), len(kept), float(r["p"]), p, abs(effect)))
    return out


LOG: dict = {}


def block(stats: Path, name: str) -> str:
    body = "\n".join(rows(stats / "tests_mse.csv", "MSE", LOG.setdefault(name, []))
                     + [r"\addlinespace"]
                     + rows(stats / "tests_time.csv", "Time", LOG.setdefault(name, [])))
    return rf"\multicolumn{{7}}{{l}}{{\textit{{{name} scale}}}} \\" + "\n" + body


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--stats", type=Path, default=Path("results/benchmark/standard/stats"))
    ap.add_argument("--stats-large", type=Path,
                    default=Path("results/benchmark/large/stats"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    body = "\n\\midrule\n".join([block(a.stats, "Standard"),
                                 block(a.stats_large, "Large")])
    name = "tab_significance.tex"
    (a.out / name).write_text(f"""% generated by experiments/benchmark/significance.py -- do not edit
\\begin{{table}}[htbp]
\\centering
\\caption{{HBC against each baseline on 28 standard-scale and 11 large-scale datasets: paired Wilcoxon tests over datasets (Section~\\ref{{sec:metric}}), Holm-corrected within each scale and metric. \\emph{{HBC wins}}: datasets on which HBC's mean is strictly lower; negative differences favor HBC.}}
\\label{{tab:significance}}
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{llccccl}}
\\toprule
\\textbf{{Baseline}} & \\textbf{{Metric}} & \\textbf{{HBC wins}} & \\textbf{{Median diff.}} & \\textbf{{Effect $r$}} & \\textbf{{$p$ (Holm)}} & \\textbf{{Favors}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")
    print(f"  {a.out / name}")
    with open(a.out / "tab_significance.log.tsv", "w") as f:
        f.write("scale\tmetric\tbaseline\tzero_pairs\tp_method\tholm_family\tp_raw\tp_holm\tr\n")
        for scale, rs in LOG.items():
            for r in rs:
                f.write("\t".join([scale] + [str(x) for x in r]) + "\n")


if __name__ == "__main__":
    main()
