#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, statistics
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

plt.rcParams["hatch.linewidth"] = 0.6
plt.rcParams.update({
    "font.size": 12, "axes.labelsize": 12, "axes.titlesize": 12,
    "xtick.labelsize": 12, "ytick.labelsize": 12, "legend.fontsize": 12,
})

METHODS = [
    ("RKM", "RKM", "#4f6228", "///"),
    ("BKMPP", "BKM++", "#d9a441", "\\\\\\"),
    ("LIMAx100", "LIMA\u00d7100", "#e8b4b2", "xxx"),
    ("TBC_repaired", "TBC", "#a98bc4", "..."),
    ("HBC", "HBC (ours)", "#1f4e79", ""),
]

METRICS = [
    ("mse", "MSE relative to best", "fig_comparison_mse", "fig:comparison_mse"),
    ("time_s", "Runtime relative to best", "fig_comparison_time",
     "fig:comparison_time"),
]

BEST_BAR_FRACTION = 0.15


def read(path: Path):
    if not path.exists():
        raise SystemExit(f"missing {path} - run the standard-scale sweep first")
    per = defaultdict(lambda: defaultdict(list))
    wanted = {name for name, *_ in METHODS}
    for r in csv.DictReader(path.open(), delimiter="\t"):
        if r["algorithm"] not in wanted:
            continue
        for metric, *_ in METRICS:
            per[metric][(r["algorithm"], r["dataset"])].append(float(r[metric]))
    return per


def panel_heights(values, datasets):
    out = []
    for d in datasets:
        present = [m for m, *_ in METHODS if (m, d) in values]
        if not present:
            continue
        best = min(statistics.median(values[(m, d)]) for m in present)
        if best <= 0:
            continue
        for m in present:
            h = statistics.median(values[(m, d)]) / best
            if np.isfinite(h):
                out.append(h)
    return out


def panel(ax, values, datasets, ylabel, tallest=1.0):
    width = 0.8 / len(METHODS)
    x = np.arange(len(datasets))

    for i, (name, label, colour, hatch) in enumerate(METHODS):
        heights, lo, hi = [], [], []
        for d in datasets:
            obs = values.get((name, d))
            best = min(statistics.median(values[(m, d)])
                       for m, *_ in METHODS if (m, d) in values)
            if not obs or best <= 0:
                heights.append(np.nan); lo.append(0); hi.append(0)
                continue
            ratios = [v / best for v in obs]
            median = statistics.median(ratios)
            heights.append(median)
            lo.append(max(median - np.percentile(ratios, 25), 0))
            hi.append(max(np.percentile(ratios, 75) - median, 0))
        tallest = max([tallest] + [h for h in heights if np.isfinite(h)])
        ax.bar(x + i * width - 0.4 + width / 2, heights, width,
               label=label, color=colour, hatch=hatch,
               edgecolor="#1a1a1a", linewidth=0.4,
               yerr=[lo, hi] if any(lo) or any(hi) else None,
               error_kw=dict(ecolor="#1a1a1a", lw=0.6, capsize=1.5))

    ax.axhline(1.0, color="#cc0000", linestyle="--", linewidth=1.8,
               dashes=(6, 4), zorder=3)
    ax.set_yscale("log")
    decades = max(np.log10(tallest), 1e-3)
    below = decades * BEST_BAR_FRACTION / (1 - BEST_BAR_FRACTION)
    ax.set_ylim(10 ** (-below), 10 ** (decades * 1.02))
    ax.set_ylabel(ylabel)
    ax.set_xticks(x)
    ax.set_xticklabels([d.replace(" ", "\n") for d in datasets],
                       rotation=60, ha="right", fontsize=12)
    ax.set_xlim(-0.6, len(datasets) - 0.4)
    ax.grid(True, axis="y", which="both", alpha=0.25, linewidth=0.5)
    ax.set_axisbelow(True)


def wrap(name: str, caption: str, label: str) -> str:
    return f"""% generated by experiments/comparison/figure.py -- do not edit
\\begin{{sidewaysfigure*}}[p]
    \\centering
    \\includegraphics[width=\\linewidth]{{generated/{name}.png}}
    \\caption{{{caption}}}
    \\label{{{label}}}
\\end{{sidewaysfigure*}}
"""


CAPTIONS = {
    "fig:comparison_mse":
        r"MSE of RKM, BKM++, LIMA$\times$100, TBC and HBC on the standard-scale "
        r"datasets, relative to the best of the five per dataset: median over "
        r"10 seeds, whiskers the interquartile range, logarithmic axis from "
        r"below $1.0$.",
    "fig:comparison_time":
        r"Runtime of RKM, BKM++, LIMA$\times$100, TBC and HBC on the "
        r"standard-scale datasets, relative to the fastest per dataset: median "
        r"over 10 seeds, whiskers the interquartile range, logarithmic axis from "
        r"below $1.0$. LIMA$\times$100 is given 100 times HBC's runtime.",
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--raw", type=Path,
                    default=Path("results/benchmark/standard/raw_runs.tsv"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    per = read(a.raw)

    common = None
    for metric, *_ in METRICS:
        for name, *_ in METHODS:
            have = {d for (m, d) in per[metric] if m == name}
            common = have if common is None else (common & have)
    if not common:
        raise SystemExit("no dataset has results for all five methods yet")
    datasets = sorted(common, key=str.lower)
    missing = {d for (_, d) in per["mse"]} - common
    if missing:
        print(f"  note: {len(missing)} dataset(s) skipped, not run by every "
              f"method: {', '.join(sorted(missing))}")

    rows = max(1, -(-len(datasets) // 16))
    per_row = -(-len(datasets) // rows)
    chunks = [datasets[i:i + per_row] for i in range(0, len(datasets), per_row)]
    inches = max(9.0, 0.62 * per_row + 2.0)

    for metric, ylabel, stem, label in METRICS:
        fig, axes = plt.subplots(rows, 1, figsize=(inches, 4.2 * rows),
                                 squeeze=False)
        tallest = max([1.0] + [h for chunk in chunks
                               for h in panel_heights(per[metric], chunk)])
        for ax, chunk in zip(axes[:, 0], chunks):
            panel(ax, per[metric], chunk, ylabel, tallest)
        handles, labels = axes[0, 0].get_legend_handles_labels()
        fig.legend(handles, labels, frameon=False, fontsize=12,
                   ncol=len(METHODS), loc="upper center",
                   bbox_to_anchor=(0.5, 1.0))
        fig.tight_layout(rect=(0, 0, 1, 0.965))
        fig.savefig(a.out / f"{stem}.png", dpi=300, bbox_inches="tight")
        print(f"  {a.out / f'{stem}.png'}")
        (a.out / f"{stem}.tex").write_text(wrap(stem, CAPTIONS[label], label))
        print(f"  {a.out / f'{stem}.tex'}")

    for metric, ylabel, *_ in METRICS:
        print(f"\n  -- {ylabel} --")
        print("  " + f"{'dataset':<20} " +
              " ".join(f"{lbl:>11}" for _, lbl, *_ in METHODS))
        for d in datasets:
            best = min(statistics.median(per[metric][(m, d)])
                       for m, *_ in METHODS)
            row = "  " + f"{d:<20} "
            for name, *_ in METHODS:
                row += f"{statistics.median(per[metric][(name, d)]) / best:>11.3f} "
            print(row)


if __name__ == "__main__":
    main()
