#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import records  # noqa: E402
import tests  # noqa: E402


def latex_table(summary: pd.DataFrame, metric: str, ours: str) -> str:
    mean_col, sd_col = f"{metric}_mean", f"{metric}_sd"
    wide_mean = summary.pivot(index="dataset", columns="algorithm", values=mean_col)
    wide_sd = summary.pivot(index="dataset", columns="algorithm", values=sd_col)

    algos = [a for a in wide_mean.columns if a != ours]
    algos = ([ours] if ours in wide_mean.columns else []) + sorted(algos)

    lines = [
        "% generated by analysis/stats/analyze.py -- do not edit by hand",
        "% bold marks the lowest mean for that dataset",
        r"\begin{tabular}{l" + "r" * len(algos) + "}",
        r"\toprule",
        "Dataset & " + " & ".join(algos.copy()) + r" \\",
        r"\midrule",
    ]

    for dataset, row in wide_mean.iterrows():
        best = row[algos].min()
        cells = []
        for algo in algos:
            mean, sd = row.get(algo), wide_sd.loc[dataset, algo]
            if pd.isna(mean):
                cells.append("--")
                continue
            cell = f"{mean:.4g} $\\pm$ {sd:.2g}" if pd.notna(sd) else f"{mean:.4g}"
            cells.append(f"\\textbf{{{cell}}}" if mean == best else cell)
        lines.append(f"{dataset} & " + " & ".join(cells) + r" \\")

    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("raw", type=Path, help="raw_runs.tsv from a sweep")
    ap.add_argument("--ours", default="HBC", help="our algorithm's label (default HBC)")
    ap.add_argument("--out", type=Path, default=Path("results/revision/analysis"))
    ap.add_argument("--strict", action="store_true",
                    help="exit non-zero if any consistency problem is found")
    args = ap.parse_args()

    df = records.load(args.raw)
    print(f"[INFO] {len(df)} records, {df['algorithm'].nunique()} algorithms, "
          f"{df['dataset'].nunique()} datasets")

    problems = records.check(df)
    for p in problems:
        print(f"[WARN] {p}")
    if problems and args.strict:
        return 1
    if not problems:
        print("[INFO] runs pair cleanly on (dataset, seed)")

    if args.ours not in set(df["algorithm"]):
        print(f"[ERROR] no records for --ours {args.ours}; "
              f"present: {sorted(df['algorithm'].unique())}")
        return 2

    args.out.mkdir(parents=True, exist_ok=True)

    summary = records.per_dataset(df)
    summary.to_csv(args.out / "summary_per_dataset.csv", index=False)

    for metric in ("mse", "time_s"):
        stem = "mse" if metric == "mse" else "time"
        result = tests.compare(df, ours=args.ours, metric=metric)
        wins = tests.win_counts(df, ours=args.ours, metric=metric)
        if not wins.empty:
            result = result.merge(wins, on="baseline", how="left")
        result.to_csv(args.out / f"tests_{stem}.csv", index=False)

        col = "mse" if metric == "mse" else "time"
        (args.out / f"table_{stem}.tex").write_text(
            latex_table(summary, col, args.ours) + "\n")

        print(f"\n== {args.ours} vs baselines on {metric} "
              f"(Wilcoxon signed-rank, one pair per dataset (mean over seeds), Holm) ==")
        cols = [c for c in ["baseline", "pairs", "ours_better", "baseline_better",
                            "median_rel_diff", "effect_r", "p_holm",
                            "significant_0.05"] if c in result.columns]
        print(result[cols].to_string(index=False))

    print(f"\n[DONE] -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
